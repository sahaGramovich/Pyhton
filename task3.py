def solve_system():
    # Матрица коэффициентов из системы уравнений
    A = [
        [1, 1, 1],
        [2, -1, 3],
        [1, 2, -1]
    ]

    # Вектор правых частей
    B = [4, 1, 3]

    print("Матрица A:")
    for row in A:
        print(row)

    print(f"\nВектор B: {B}")

    # Вычисляем определитель матрицы A
    det_A = (A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1]) -
             A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0]) +
             A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]))

    print(f"\nОпределитель матрицы A: {det_A}")

    if det_A == 0:
        print("Система не имеет единственного решения")
        return

    # Вычисляем обратную матрицу A⁻¹
    inv_A = [
        [
            (A[1][1] * A[2][2] - A[1][2] * A[2][1]) / det_A,
            (A[0][2] * A[2][1] - A[0][1] * A[2][2]) / det_A,
            (A[0][1] * A[1][2] - A[0][2] * A[1][1]) / det_A
        ],
        [
            (A[1][2] * A[2][0] - A[1][0] * A[2][2]) / det_A,
            (A[0][0] * A[2][2] - A[0][2] * A[2][0]) / det_A,
            (A[0][2] * A[1][0] - A[0][0] * A[1][2]) / det_A
        ],
        [
            (A[1][0] * A[2][1] - A[1][1] * A[2][0]) / det_A,
            (A[0][1] * A[2][0] - A[0][0] * A[2][1]) / det_A,
            (A[0][0] * A[1][1] - A[0][1] * A[1][0]) / det_A
        ]
    ]

    print("\nОбратная матрица A⁻¹:")
    for row in inv_A:
        print([round(x, 4) for x in row])

    # Вычисляем решение: X = A⁻¹ · B
    X = [0, 0, 0]
    for i in range(3):
        for j in range(3):
            X[i] += inv_A[i][j] * B[j]

    # Округляем до одного знака после запятой
    X_rounded = [round(x, 1) for x in X]

    print(f"\nРешение системы:")
    print(f"x = {X_rounded[0]}")
    print(f"y = {X_rounded[1]}")
    print(f"z = {X_rounded[2]}")

    print(f"\nВектор-решение X = {X_rounded}")

    # Проверка решения
    print("\nПроверка:")
    x, y, z = X_rounded
    eq1 = x + y + z
    eq2 = 2 * x - y + 3 * z
    eq3 = x + 2 * y - z

    print(f"1-е уравнение: {x} + {y} + {z} = {eq1} (должно быть 4)")
    print(f"2-е уравнение: 2*{x} - {y} + 3*{z} = {eq2} (должно быть 1)")
    print(f"3-е уравнение: {x} + 2*{y} - {z} = {eq3} (должно быть 3)")


# Запускаем решение
solve_system()