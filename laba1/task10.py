
a = int(input("Введите целое число a: "))
b = int(input("Введите целое число b: "))


print(f"\nРезультаты математических операций:")
print(f"Сумма {a} + {b} = {a + b}")
print(f"Разность {a} - {b} = {a - b}")
print(f"Произведение {a} * {b} = {a * b}")


if b != 0:
    print(f"Частное от деления {a} / {b} = {a / b}")
    print(f"Остаток от деления {a} % {b} = {a % b}")
else:
    print("Частное от деления: невозможно (деление на ноль)")
    print("Остаток от деления: невозможно (деление на ноль)")


print(f"Результат возведения числа {a} в степень {b} = {a ** b}")